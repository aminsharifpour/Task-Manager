import {avatarMembersRouter} from "./accounts/avatar-router.js";
import {minuteAttachmentsRouter} from "./minutes/attachments-router.js";
import { Router } from "express";
import * as teams from "./teams/service.js";
import * as tasks from "./tasks/service.js";
import * as minutes from "./minutes/service.js";
import * as hr from "./hr/service.js";
import * as accounting from "./accounting/service.js";
import * as chat from "./chat/service.js";
import * as notifications from "./notifications/service.js";
import { prisma, ensureModule, defaultModules, mutate, audit, DomainError, requireInternal } from "./shared/scoped.js";
import { requireAdmin } from "./organizations/policy.js";
import { getProject } from "./organizations/service.js";
import { normalizeSteps, validateStepMembers } from "./tasks/workflow.js";
import * as projects from "./projects/service.js";
import { projectTemplates } from "./projects/definitions.js";
import { filesRouter } from "./files/router.js";
import { chatAttachmentsRouter } from "./chat/attachments-router.js";
import { organizationOperationsRouter } from "./operations/router.js";
import { taskCoreRouter } from "./tasks/core-router.js";

export function legacyModulesRouter(){
  const r=Router();
  r.use(avatarMembersRouter());
  r.use(filesRouter());
  r.use(minuteAttachmentsRouter());
  r.use(chatAttachmentsRouter());
  r.use(taskCoreRouter());
  r.use(organizationOperationsRouter());
  const wrap=(fn,status=200)=>async(req,res,next)=>{try{if(req.body!==undefined&&(!req.body||typeof req.body!=="object"||Array.isArray(req.body)))throw new DomainError(400,"INVALID_INPUT","درخواست معتبر نیست.");res.status(status).json(await fn(req.organization,req));}catch(e){next(e);}};
  r.get("/module-settings",wrap(async(c)=>{const configured={...defaultModules,...(await prisma.organizationSetting.findUnique({where:{organizationId:c.organizationId}}))?.modules},org=await prisma.organization.findUnique({where:{id:c.organizationId},select:{allowedModules:true,calendar:true,timezone:true}});configured.accounting=false;return {modules:Object.fromEntries(Object.entries(configured).map(([key,value])=>[key,value&&org.allowedModules?.[key]!==false])),configuredModules:configured,calendar:org.calendar,timezone:org.timezone,permissions:{userId:c.userId,role:c.role,canManageHr:c.canManageHr,canManageAccounting:c.canManageAccounting}};}));
  r.put("/module-settings",wrap(async(c,req)=>{requireAdmin(c);if(c.role!=="owner")throw new DomainError(403,"PERMISSION_DENIED","تنظیم بخش‌ها با مالک است.");const modules={...defaultModules};for(const [key,value]of Object.entries(req.body.modules||{})){if(!Object.hasOwn(modules,key)||typeof value!=="boolean")throw new DomainError(400,"INVALID_MODULE_SETTING","تنظیم بخش معتبر نیست.");modules[key]=value;}modules.accounting=false;return mutate(c,null,async(tx,current)=>{requireAdmin(current);if(current.role!=="owner")throw new DomainError(403,"PERMISSION_DENIED","مجوز کافی نیست.");const row=await tx.organizationSetting.upsert({where:{organizationId:current.organizationId},create:{organizationId:current.organizationId,modules},update:{modules}});await audit(tx,current,"organization.modules_updated",current.organizationId);return row;});}));
  // The tenant context is already resolved by the organizations router. No legacy global route is reopened.
  for(const prefix of ["members","teams","tasks","minutes","hr","accounting","chat","notifications","notification-preferences"]){
    const module=prefix==="members"?"teams":prefix==="notification-preferences"?"notifications":prefix;
    r.use("/"+prefix,async(req,res,next)=>{try{if(prefix!=="members"||req.method!=="GET")await ensureModule(req.organization,module);next();}catch(e){next(e);}});
  }
  r.get("/members",wrap((c,q)=>teams.listMembers(c,q.query)));
  r.post("/members/:userId/reactivate",wrap((c,q)=>teams.reactivateMember(c,q.params.userId,q.body||{})));
  r.post("/teams/:id/restore",wrap((c,q)=>teams.restoreTeam(c,q.params.id)));
  r.post("/members",wrap((c,q)=>teams.createMember(c,q.body),201));
  r.patch("/members/:userId",wrap((c,q)=>teams.updateMember(c,q.params.userId,q.body)));
  r.get("/teams",wrap((c,q)=>teams.listTeams(c,q.query)));
  r.post("/teams",wrap((c,q)=>teams.saveTeam(c,null,q.body),201));
  r.patch("/teams/:id",wrap((c,q)=>teams.saveTeam(c,q.params.id,q.body)));
  r.delete("/teams/:id",wrap((c,q)=>teams.archiveTeam(c,q.params.id)));
  r.post("/teams/:id/members",wrap((c,q)=>teams.teamMember(c,q.params.id,q.body.userId)));
  r.delete("/teams/:id/members/:userId",wrap((c,q)=>teams.teamMember(c,q.params.id,q.params.userId,true)));
  r.get("/project-templates",wrap(c=>{requireInternal(c);return projectTemplates;}));
  r.patch("/projects/:id",wrap((c,q)=>projects.update(c,q.params.id,q.body)));
  r.get("/tasks",wrap((c,q)=>tasks.listTasks(c,q.query)));
  r.post("/tasks",wrap((c,q)=>tasks.createTask(c,q.body),201));
  r.get("/tasks/:id",wrap((c,q)=>tasks.readTask(c,q.params.id)));
  r.patch("/tasks/:id",wrap((c,q)=>tasks.updateTask(c,q.params.id,q.body)));
  r.delete("/tasks/:id",wrap((c,q)=>tasks.deleteTask(c,q.params.id,q.body.expectedVersion)));
  r.post("/tasks/:id/workflow/comments",wrap((c,q)=>tasks.addComment(c,q.params.id,q.body),201));
  r.post("/tasks/:id/workflow/decision",wrap((c,q)=>tasks.decide(c,q.params.id,q.body)));
  r.get("/tasks/:id/workflow/history",wrap((c,q)=>tasks.history(c,q.params.id)));
  r.get("/minutes",wrap((c,q)=>minutes.list(c,q.query)));
  r.get("/minutes/:id",wrap((c,q)=>minutes.detail(c,q.params.id)));
  r.post("/minutes",wrap((c,q)=>minutes.save(c,null,q.body),201));
  r.patch("/minutes/:id",wrap((c,q)=>minutes.save(c,q.params.id,q.body)));
  r.patch("/minutes/:id/archive",wrap((c,q)=>minutes.archive(c,q.params.id,q.body)));
  r.delete("/minutes/:id",wrap((c,q)=>minutes.remove(c,q.params.id)));
  r.get("/hr/report",wrap((c,q)=>hr.report(c,q.query)));
  r.get("/accounting/report",wrap((c,q)=>accounting.report(c,q.query)));
  r.get("/hr/profiles",wrap((c,q)=>hr.profiles(c,q.query)));
  r.get("/hr/profiles/:userId",wrap((c,q)=>hr.profile(c,q.params.userId)));
  r.put("/hr/profiles/:userId",wrap((c,q)=>hr.saveProfile(c,q.params.userId,q.body)));
  r.get("/hr/leaves",wrap((c,q)=>hr.leaves(c,q.query)));
  r.post("/hr/leaves",wrap((c,q)=>hr.requestLeave(c,q.body),201));
  r.patch("/hr/leaves/:id/status",wrap((c,q)=>hr.reviewLeave(c,q.params.id,q.body)));
  r.get("/hr/attendance",wrap((c,q)=>hr.attendance(c,q.query)));
  r.put("/hr/attendance/:userId/:date",wrap((c,q)=>hr.saveAttendance(c,q.params.userId,q.params.date,q.body)));
  r.delete("/hr/attendance/:id",wrap((c,q)=>hr.deleteAttendance(c,q.params.id)));
  r.get("/accounting/accounts",wrap((c,q)=>accounting.accounts(c,q.query)));
  r.post("/accounting/accounts",wrap((c,q)=>accounting.saveAccount(c,null,q.body),201));
  r.patch("/accounting/accounts/:id",wrap((c,q)=>accounting.saveAccount(c,q.params.id,q.body)));
  r.delete("/accounting/accounts/:id",wrap((c,q)=>accounting.removeAccount(c,q.params.id)));
  r.get("/accounting/transactions",wrap((c,q)=>accounting.transactions(c,q.query)));
  r.post("/accounting/transactions",wrap((c,q)=>accounting.saveTransaction(c,null,q.body),201));
  r.patch("/accounting/transactions/:id",wrap((c,q)=>accounting.saveTransaction(c,q.params.id,q.body)));
  r.delete("/accounting/transactions/:id",wrap((c,q)=>accounting.removeTransaction(c,q.params.id)));
  r.get("/accounting/budgets",wrap((c,q)=>accounting.budgets(c,q.query)));
  r.put("/accounting/budgets/:month",wrap((c,q)=>accounting.setBudget(c,q.params.month,q.body)));
  r.get("/accounting/budget-history",wrap((c,q)=>accounting.budgetHistory(c,q.query)));
  r.get("/chat/conversations",wrap((c,q)=>chat.list(c,q.query)));
  r.get("/chat/inbox-summary",wrap((c)=>chat.inboxSummary(c)));
  r.get("/chat/conversations/:id",wrap((c,q)=>chat.detail(c,q.params.id)));
  r.patch("/chat/conversations/:id/inbox",wrap((c,q)=>chat.saveInbox(c,q.params.id,q.body)));
  r.post("/chat/conversations",wrap((c,q)=>chat.create(c,q.body),201));
  r.patch("/chat/conversations/:id",wrap((c,q)=>chat.update(c,q.params.id,q.body)));
  r.delete("/chat/conversations/:id",wrap((c,q)=>chat.remove(c,q.params.id)));
  r.get("/chat/conversations/:id/messages",wrap((c,q)=>chat.messages(c,q.params.id,q.query)));
  r.post("/chat/conversations/:id/messages",wrap((c,q)=>chat.send(c,q.params.id,q.body),201));
  r.post("/chat/conversations/:id/read",wrap((c,q)=>chat.markRead(c,q.params.id)));
  r.patch("/chat/messages/:id",wrap((c,q)=>chat.editMessage(c,q.params.id,q.body)));
  r.delete("/chat/messages/:id",wrap((c,q)=>chat.editMessage(c,q.params.id,{},true)));
  r.post("/chat/messages/:id/reactions",wrap((c,q)=>chat.react(c,q.params.id,q.body)));
  r.get("/notifications",wrap((c,q)=>notifications.list(c,q.query)));
  r.get("/notifications/summary",wrap((c)=>notifications.summary(c)));
  r.post("/notifications/bulk/:operation",wrap((c,q)=>notifications.bulk(c,q.params.operation)));
  r.post("/notifications/:id/:operation",wrap((c,q)=>notifications.change(c,q.params.id,q.params.operation)));
  r.get("/notification-preferences",wrap((c)=>notifications.preference(c)));
  r.put("/notification-preferences",wrap((c,q)=>notifications.savePreference(c,q.body)));
  r.get("/dashboard",wrap(async(c)=>{await ensureModule(c,"tasks");requireInternal(c);const statuses=await prisma.task.groupBy({by:["status"],where:tasks.visibleTasks(c),_count:{_all:true}});return {statuses,overdue:await prisma.task.count({where:{...tasks.visibleTasks(c),isDone:false,executionDate:{lt:new Date()}}}),myTasks:await prisma.task.count({where:{...tasks.visibleTasks(c),assigneePrimaryId:c.userId,isDone:false}})};}));
  return r;
}


